"""Separation of the final answer from gpt-oss reasoning."""

import re

from server.contracts.domain_errors import LlmRequestError

CHANNEL_HEADER = re.compile(r"<\|channel\|>([a-z]+)[^<]*(?:<\|constrain\|>[^<]*)?<\|message\|>")
FINAL_CHANNEL = "final"
CLOSING_TAGS = ("<|return|>", "<|end|>")


def extract_final_answer(generated_text: str) -> str:
    """Keep only the last final channel of a gpt-oss harmony reply.

    Usage:
        Call on the generated text, decoded with its special tokens. Reasoning
        is written to the analysis channel and is never returned. The header
        may carry a format hint such as "<|constrain|>json".

    Args:
        generated_text: Text generated by the model.

    Returns:
        The final answer, never empty.

    Raises:
        LlmRequestError: If the reply has no final answer. The message lists
            the channels found, and no generated content.
    """
    channel_headers = list(CHANNEL_HEADER.finditer(generated_text))
    if not channel_headers or channel_headers[-1].group(1) != FINAL_CHANNEL:
        channel_names = [channel_header.group(1) for channel_header in channel_headers]
        raise LlmRequestError(f"LLM reply has no final answer, channels: {channel_names}")
    final_text = generated_text[channel_headers[-1].end() :].strip()
    for closing_tag in CLOSING_TAGS:
        final_text = final_text.removesuffix(closing_tag).strip()
    if not final_text:
        raise LlmRequestError("LLM reply has an empty final answer")
    return final_text
